<h2>申请步骤</h2>
<h3>第一步：注册账号</h3>
<p>进入 <a href="https://bailian.console.aliyun.com/" target="_blank" rel="noopener noreferrer">阿里云百炼</a>，根据提示注册或登陆账号。</p>
<h3>第二步：创建 API 密钥</h3>
<p>进入 <a href="https://bailian.console.aliyun.com/?apiKey=1#/api-key" target="_blank" rel="noopener noreferrer">API Key</a>，点击【创建我的 API Key】，复制后备用。</p>
<h3>第三步：挑选模型</h3>
<p>进入 <a href="https://bailian.console.aliyun.com/" target="_blank" rel="noopener noreferrer">阿里云百炼</a> 导航中的 <strong>模型广场</strong>，点击模型类型里的【文本生成】，在下方列表点击需要的模型的【查看详情】，在详细页面的模型名称的下方显示的字符串便是模型名代号。</p>