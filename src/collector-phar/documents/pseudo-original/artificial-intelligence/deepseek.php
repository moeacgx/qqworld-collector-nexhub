<h2>申请步骤</h2>
<h3>第一步：注册账号</h3>
<p>进入 <a href="https://platform.deepseek.com/" target="_blank" rel="noopener noreferrer">DeepSeek 开放平台</a>，根据提示注册或登陆账号。</p>
<h3>第二步：创建 API 密钥</h3>
<p>进入 <a href="https://platform.deepseek.com/api_keys" target="_blank" rel="noopener noreferrer">API Keys</a>，点击【创建 API Key】，填写名称“网站助手”后即可创建新的 API key，填到插件设置里即可。</p>