<h2>申请步骤</h2>
<h3>第一步：注册账号</h3>
<p>进入 <a href="https://console.bce.baidu.com/" target="_blank" rel="noopener noreferrer">百度智能云开发平台</a>，根据提示注册或登陆账号。</p>
<h3>第二步：创建 API 密钥</h3>
<p>进入 <a href="https://console.bce.baidu.com/iam/#/iam/apikey/list" target="_blank" rel="noopener noreferrer">API Key</a>，点击【创建API Key】，复制后备用。</p>
<h3>第三步：创建应用</h3>
<p>进入 <a href="https://console.bce.baidu.com/qianfan/ais/console/applicationConsole/application" target="_blank" rel="noopener noreferrer">应用接入</a>，点击【创建应用】，复制后备用。</p>
<h3>第四步：挑选模型</h3>
<p>进入 <a href="https://console.bce.baidu.com/qianfan/modelcenter/model/buildIn/list" target="_blank" rel="noopener noreferrer">模型广场</a>，点击类别里的 【文本生成】，在右侧列表点击需要的模型，在 <em>版本列表</em> 里可以找到 <em>模型名称</em>。</p>