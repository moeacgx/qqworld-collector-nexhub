<h2>设置</h2>
<h4>开启</h4>
<p>不开启就不会打上水印喔。</p>
<h4>模式</h4>
<p>有三种模式</p>
<ol>
	<li><strong>正常</strong>：可以设置对齐方式；</li>
	<li><strong>随机位置</strong>：不能设置对齐方式，水印会随机打在图片的任何可能的位置上；</li>
	<li><strong>重复铺满</strong>：整齐地重复平铺在图片上，对水印图片的要求是，上下左右要留空白，否则就会挤在一起把图片完全挡住；</li>
</ol>
<h4>对齐方式</h4>
<p>只有普通模式才能选择。</p>
<h4>位置</h4>
<p>只有普通模式才能用来手动微调图片的相对位置。</p>
<h4>偏移</h4>
<p>当前水印的相对位置，不能设置。</p>
<h4>不透明度</h4>
<p>设置半透明水印。</p>
<h4>上传水印图片</h4>
<p>注意，如果使用了云存储并且勾选了同步后删除本地附件时，会导致本地水印文件被删除，所以图片水印也就失效了。</p>
<h4>宽度限制</h4>
<p>默认水印的宽度不会超过照片宽度的30%，方便水印在不同尺寸的图片上显示方式更具适应性。</p>