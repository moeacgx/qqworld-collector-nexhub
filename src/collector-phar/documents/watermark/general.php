<p>可以同时使用图片水印和文字水印，当然一般都不会这么做。</p>
<h2>通用设置</h2>
<h4>忽略GIF动画</h4>
<p>给GIF动画打水印很难，除非你想把GIF动画变成单帧图片，不要取消这个。</p>
<h4>扫描</h4>
<p>扫描媒体库并自动给允许的图像添加水印，不会处理已经添加了水印的图像。</p>
<p>但如果你的网站图片在使用本插件之前就打了水印，请不要使用扫描功能</p>
<h4>启用模式</h4>
<p>有三种模式可选，分别是自动保存图片的时候、在编辑页上传图像的时候以及在媒体库页面上传图像的时候给图片打水印。</p>
<h4>启用的缩略图尺寸</h4>
<p>默认只会给完整尺寸图片打水印。</p>
<h4>按尺寸过滤</h4>
<p>默认是300x300，会忽略比这个尺寸更小的图像。</p>
<h4>按URL过滤</h4>
<p>如果不希望在抓取某些网站上的图片上打水印，可以添加该网站的域名关键词进行忽略。</p>