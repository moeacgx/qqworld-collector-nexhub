<h2>设置</h2>
<h4>开启</h4>
<p>不开启就不会打上水印喔。</p>
<h4>预览</h4>
<p>除了字体效果，都可以预览个八九不离十。</p>
<h4>内容</h4>
<p>水印的内容，一般是网站名。</p>
<h4>字体颜色</h4>
<p>水印的字体颜色。</p>
<h4>字体</h4>
<p>默认是没有字体的，需要将喜欢的字体上传到 <strong>/wp-content/font/</strong> 目录中，然后再回来刷新页面就能看到并选择。</p>
<h4>背景宽度</h4>
<p>字体会有一个背景色，最初是为了挡住微信图片水印的。</p>
<h4>背景颜色</h4>
<p>不解释。</p>
<h4>背景不透明度</h4>
<p>可以设置半透明的背景。</p>
<h4>背景马赛克</h4>
<p>把背景所覆盖的区域打上马赛克，进一步弱化已有水印的效果。</p>