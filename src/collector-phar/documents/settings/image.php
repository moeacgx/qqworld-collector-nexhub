<h2>禁用缩略图尺寸</h2>
<p>很多用户认为Wordpress生成太多的缩略图尺寸，过多地占据了服务器硬盘空间。</p>
<h2>图片压缩选项</h2>
<p>一般不需要开启，默认就是最好的75%压缩。</p>
<p>开启后使用插件内置的图片压缩功能，只能对JPEG格式进行较有效的压缩，而对PNG压缩能力有限，无法对GIF进行压缩。所以推荐安装 <a href="https://wordpress.org/plugins/tiny-compress-images/" target="_blank">Compress JPEG & PNG images</a>。</p>
<h2>辅助设置</h2>
<h4>显示特色图片</h4>
<p>在后台文章列表栏目中显示特色图片。</p>
<h4>显示上传的图像</h4>
<p>在后台文章列表栏目中显示上传的图像。</p>
<h4>显示内部的图像</h4>
<p>在后台文章列表栏目中显示内部的图像，包括远程图片。</p>