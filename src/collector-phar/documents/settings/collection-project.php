<h2>检测重复标题</h2>
<p>在编辑页输入标题后自动检测该标题是否重复，并将重复的文章列出。</p>
<h2>收藏项目</h2>
<p>这里是和收藏项目有关的设置。</p>
<h4>显示已采集文章数量</h4>
<p>在收藏项目列表页显示已采集到的文章数量，如果你已经采集了大量的文章，且服务器性能不足导致打开收藏项目列表的速度非常慢，可以考虑禁用它。</p>
<h4>随机作者</h4>
<p>设置随机作者名，可以输入字符串，系统将自动新建用户，也可以输入已经存在的用户ID，每行一个。</p>