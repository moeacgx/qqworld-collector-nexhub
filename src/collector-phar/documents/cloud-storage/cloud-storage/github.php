<h1>快速开始</h1>
<h2>新建 GitHub 仓库</h2>
<p>点击链接创建一个用来存储图片的 <a href="https://github.com/new" target="_blank">GitHub</a> 仓库 ，仓库属性必须选 <strong>Public</strong>。</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>cloud-storage/cloud-storage/github/1.png" /></p>
<h2>新建 GitHub Token</h2>
<p>点击链接创建一个带有 <strong>repo</strong> 权限的 <a href="https://github.com/settings/tokens/new" target="_blank">GitHub Token</a>。<strong>Note</strong> 随便填，<strong>过期时间 Expiration</strong> 设置为 <strong>永不过期 No expiration</strong>，然后勾选下面的 <strong>repo</strong> 即可。</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>cloud-storage/cloud-storage/github/2.png" /></p>
<p class="qq-icon info">注意：新生成的 Token 只会显示一次，请妥善保存，如有遗失，重新生成即可。</p>