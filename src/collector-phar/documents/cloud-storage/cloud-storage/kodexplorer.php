<h2>安装方法<h2>
<h3>新建网站</h3>
<p>建立云存储的网站，并配置好二级域名。</p>
<h3>下载并解压</h3>
<p>下载地址：<a href="https://kodcloud.com/download/" target="_blank">https://kodcloud.com/download/</a></p>
<p>将程序文件解压到云存储网站的根目录。</p>
<h3>安装云存储</h3>
<p>该云存储不需要数据库，只需要设置管理员密码即可。</p>
<h2>设置方法</h2>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>cloud-storage/cloud-storage/kodexplorer/1.png" /></p>
<h3>设置域名和目录</h3>
<p>填写云存储的域名以及个人主页的目录路径作为目录。</p>
<p>这里最好给上传的主目录绑定域名，否则直接使用云存储的地址就需要将目录的路径也写进去，比如：</p>
<pre class="prism"><code class="language-php">http://kodexplorer.gov/data/User/admin/home</code></pre>
<h3>设置可道云首页</h3>
<p>填写云存储的首页地址。</p>
<p>有人可能会问，为什么要设置两次有道云的首页地址？这是因为可以给自己的个人主页目录绑定域名。</p>
<h3>设置用户名和密码</h3>
<p>填写你的用户名和密码，用来获得上传权限以及上传目录。</p>
<h1>注意</h1>
<p>仅支持旧版可道云，新版使用的是虚拟地址。可以在百度搜索 <strong>可道云4.0</strong> 找到旧版程序，最新的旧版是 <em>4.40</em>。</p>