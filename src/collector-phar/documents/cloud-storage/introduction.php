<h2>注意事项</h2>
<h4>扫描媒体库</h4>
<p>如果有旧的文章需要快速同步到云储存，请确保所有本地图片的地址都是绝对地址，否则在扫描的时候是无法自动替换的。不过就算是相对地址也没关系，可以在扫描之后使用本插件的数据库功能进行人工替换。</p>
<h2>手动同步媒体库</h2>
<p>在 <a href="<?php print admin_url('upload.php?mode=list'); ?>" target="_blank">媒体库列表模式</a> 下可以手动同步。</p>
<h4>同步网站资源</h4>
<p>如果使用宝塔面板，不要开启强制HTTPS，会导致回源失败。</p>
<h4>CDN</h4>
<p>如果使用CDN，可能需要在CDN的HTTP Header设置里添加 <em>Access-Control-Allow-Origin:*</em> 才能支持跨域访问字体。</p>