<p>为缓解服务器带宽压力，很多网站会将资源放在云存储上。</p>
<h2>云存储</h2>
<h4>付费云存储</h4>
<p>这类云存储可以保存所有格式的文件，管理起来也比较方便，所以还可以将网站的所有资源如CSS，JS文件都同步到云端。在媒体库的列表页有手动同步和再次同步的按钮。</p>
<ul>
	<li>七牛云存储（QINIU）</li>
	<li>阿里云开放存储服务（OSS）</li>
	<li>腾讯对象存储服务（COS）</li>
	<li>又拍云存储（UPYUN）</li>
	<li>百度对象存储（BOS）</li>
	<li>UCloud对象存储（UFile）</li>
</ul>
<h4>免费云存储</h4>
<p>这类云存储，除了FTP的特性和付费云存储一样之外，大多都只能保存图片资源。在媒体的列表页也有同步的按钮，同步之后还可以还原（前提是本地附件并没有被删除）。</p>
<ul>
	<li>文件传输协议（FTP）</li>
	<li>新浪图床</li>
	<li>贴图库云存储服务</li>
	<li>SM.MS图床</li>
	<li>路过图床</li>
	<li>简单图床</li>
	<li>免费图床</li>
	<li>68图床</li>
	<li>淡然图床</li>
</ul>
