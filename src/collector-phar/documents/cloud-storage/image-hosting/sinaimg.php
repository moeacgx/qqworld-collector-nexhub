<p>新浪图床，因为其优秀的速度受到很多站长的青睐，并将其作为自己自媒体网站的首选云存储。</p>
<h2>设置方法</h2>
<p>默认需要设置Cookies才能运行，也可以使用自动登录方式获取Cookie。</p>
<p>首先登陆<a href="https://www.weibo.com/" target="_blank">微博</a>后获取Cookies。</p>
<p><a href="<?php print admin_url('admin.php?page=qqworld-collector-documents#tips--get-cookies'); ?>" target="_blank" class="button button-primary button-large qc-icon link">如何获取Cookies</a></p>
<p>先填写Cookies，注意：Cookies的有效期可能只有1天，如果无法同步到图床，请更新Cookies。</p>
<p>填好之后保存设置，去媒体库列表页手动同步1个附件试试，如果成功了，再回到设置页扫描媒体库。</p>
<h2>注意</h2>
<p>新浪图床已开启防盗链，如果开启该云存储，则会自动在页面里输出 <em>&lt;meta name="referrer" content="no-referrer"&gt;</em> 来破解，副作用是，无法统计访问情况。</p>