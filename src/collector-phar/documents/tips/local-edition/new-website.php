<p>在 <strong>Visual-AMP</strong> 左侧导航栏里点鼠标右键，在弹出的菜单中点击 <strong>添加网站...</strong>。</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>tips/local-edition/new-website/1.png" /></p>
<ol>
	<li>首先起个 <strong>站点名称</strong>，这个方便自己辨识即可。</li>
	<li>然后在 <strong>物理路径</strong> 中 <strong>选择一个目录</strong> 来存放站点文件，自己决定。</li>
	<li><strong>主机名</strong> 填写 <em>q.c</em>，你也可以写二级域名如：<em>1.q.c</em>，右边的 <strong>ServerAlias（服务别名）</strong>可以不写，也可以写其他二级域名，总之所有设置的域名都将指向这个站点。</li>
</ol>