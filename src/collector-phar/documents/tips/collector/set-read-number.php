<p>阅读量一般是保存在自定义字段里的，所以首先需要知道主题的阅读量的自定义字段名（查看设置页阅读量输入框的源代码或者咨询主题作者），比如<strong>read</strong>。</p>
<p>然后就可以在采集项目里设置自定义字段，使用随机数方法，然后填写随机数范围。</p>
<p>最后填写要保存的自定义字段名即可以及说明名称即可。</p>
