<h2>常规过滤</h2>
<p>水印常规设置会限制某些情况下不打水印，如果碰到有些图片没有打水印的情况，请检查常规设置，能打开的都打开。</p>
<h3>启用模式</h3>
<p>系统可以分辨三种情况来加水印，分别是自动保存图片时，在编辑页上传图片时以及媒体库上传图片时。</p>
<h3>缩略图尺寸</h3>
<p>默认只会给完整尺寸添加水印哦。</p>
<h3>按URL过滤</h3>
<p>注意，上传的图片时没有URL的，所以不适用。</p>
<h2>文字水印</h2>
<p>是需要上传字体的，不推荐使用文字水印，这个主要是用来挡住微信图片水印的，其实用好看的图片水印也可以做到。</p>
