<h2>使用手动模式</h2>
<p>手动模式是付费版的卖点之一，可以多线程抓图，可以在 <strong>设置</strong> - <strong>服务器</strong> 的 <a href="<?php print admin_url('admin.php?page=qqworld-collector-settings#server'); ?>" target="_blank"><strong>服务器压力</strong></a> 里根据你的服务器性能设置速度。</p>
<h2>优先填写文章标题</h2>
<p>请尽量填写文章标题之后再抓图，会提高程序的兼容性。</p>
<h2>重复保存图片</h2>
<p>强烈建议检查是否有其他插件也开启了抓图功能，有些主题也可以抓图，关掉即可。</p>