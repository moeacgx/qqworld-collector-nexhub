<p>现在的新版浏览器基本都支持WEBP格式了，全面使用WEBP格式已提上日程。本工具将帮助大家将媒体库中的图片批量转换为WEBP格式。</p>
<h2>自动转换</h2>
<h4>选择文章类型</h4>
<p>这个是必选的，否则无法进行。</p>
<h4>转换为</h4>
<p>选择要转换为的文件类型。</p>
<h4>扫描所选图像</h4>
<p>批量扫描媒体库，将指定文件类型的附件批量转换为指定的文件格式。</p>
<h2>手动转换</h2>
<p>在 <a href="<?php print admin_url('upload.php?mode=list'); ?>" target="_blank">媒体库列表页</a> 可以勾选要转换的附件，在 <strong>批量操作</strong> 的下拉菜单中选择 <em>转换为WEBP格式</em> 或 <em>转换为JPEG格式</em> 的动作，并点击 <strong>应用</strong> 按钮进行批量转换。</p>