<h2>排除法</h2>
<p>即使是编程高手，也会首选排除法来定位问题根源。</p>
<h3>一、逐个禁用插件</h3>
<p>如果禁用了某个插件，问题就消失了，即可判定为该插件的程序问题。</p>
<h3>二、切换官方主题</h3>
<p>Wordpress官方出的主题是以年份命名的，通常兼容性最好，如果切换到官方主题问题消失，即可判定为主题的问题。</p>
<h2>进一步排查</h2>
<p>通过排除法找到了问题主要根源，无论是插件或是主题，想办法禁用插件或主题的部分功能，进行进一步排查。</p>
<p>如果关闭了某个功能，问题消失，即可判断为该功能的问题，至少是相关。</p>
<h2>提交问题</h2>
<p>将排查的结果上报给作者。</p>