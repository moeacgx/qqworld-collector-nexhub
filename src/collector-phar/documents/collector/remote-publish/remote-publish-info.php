<p>在 <strong>设置</strong> - <a href="<?php print admin_url('admin.php?page=qqworld-collector-settings#home'); ?>" target="_blank"><strong>远程站点</strong></a> 中建立了远程站点后，即可在 <a href="<?php print admin_url('edit.php?post_type=qqworld-collections'); ?>" target="_blank"><strong>收藏项目</strong></a> 之上看到 远程发布 菜单。</p>
<p>该功能属于 <strong>远程发布控制面板</strong>，可以将网站的内容批量发布到远程站点。</p>
<h2>注意事项</h2>
<ul>
	<li>选择 <strong>远程站点</strong> 后才能进行发布。</li>
	<li><strong>远程站点</strong> 也必须安装 <strong>QQWorld收藏家豪华版</strong> 并且用相同的序列号激活，否则可能会导致数据投送不全，或者有多余的反斜杠(\)出现。</li>
	<li>如果 <strong>远程站点</strong> 安装的优化插件禁用了 <em>XMLRPC</em>，会导致远程发布到 <em>WordPress</em> 失败（<strong>405</strong> 错误）。</li>
</ul>