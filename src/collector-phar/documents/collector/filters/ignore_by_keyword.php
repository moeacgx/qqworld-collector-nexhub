<h4>允许的关键词</h4>
<p>如果采集到的内容不包含该关键词，则整条文章将被忽略掉。</p>
<h4>禁止的关键词</h4>
<p>如果采集到的内容包含该关键词，则整条文章将被忽略掉。</p>
<h4>空的</h4>
<p>如果采集到的内容是空的，则整条文章将被忽略掉。</p>