<p>通常用于采集下载站，将文件保存到本地或媒体库，然后将链接保存到自定义字段中。</p>
<h4>不经过媒体库</h4>
<p>保存到本地，可以不受媒体库文件类型的限制。</p>
<h4>保存到媒体库</h4>
<p>返回媒体库附件的地址，所以只能保存媒体库所支持的文件类型。</p>
<h4>人工下载</h4>
<p>事先生成本地URL，并输出下载URL记录，然后使用下载工具批量下载后手动上传。</p>