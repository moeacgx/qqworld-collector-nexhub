<p>目前快捷键只在 <strong>采集列表</strong>、<strong>采集正文</strong> 和 <strong>采集评论</strong> 有效。</p>
<h1>快捷键</h1>
<h2>采集列表专用</h2>
<dl>
	<dt>ctrl + shift + 1</dt>
	<dd>插入采集项目：<strong>文章链接</strong>、<strong>文章标题</strong>。</dd>
	<dt>ctrl + shift + 2</dt>
	<dd>插入采集项目：<strong>文章链接</strong>、<strong>文章标题</strong>、<strong>特色图片</strong>。</dd>
	<dt>ctrl + shift + 3</dt>
	<dd>插入采集项目：<strong>文章链接</strong>、<strong>文章标题</strong>、<strong>文章摘要</strong>、<strong>特色图片</strong>。</dd>
</dl>
<h2>采集正文专用</h2>
<dl>
	<dt>ctrl + shift + 4</dt>
	<dd>插入采集项目：<strong>文章标题</strong>、<strong>文章内容</strong>、<strong>分类法</strong></dd>
</dl>
<h2>采集评论专用</h2>
<dl>
	<dt>ctrl + shift + 5</dt>
	<dd>插入采集项目：<strong>评论者名称</strong>、<strong>评论内容</strong>、<strong>评论日期</strong></dd>
</dl>
<h2>通用</h2>
<dl>
	<dt>ctrl + shift + 0</dt>
	<dd>删除当前页所有采集项目。</dd>
</dl>