<h4>发布状态</h4>
<p>保存的时候设置的文章发布状态，默认是<strong>等待复审</strong>。</p>
<h4>保存远程附件 &amp; 设置特色图片</h4>
<p>开启后才会在保存文章的时候自动保存内容中的远程附件。</p>
<h4>无序</h4>
<p>采集到的文章在保存前将被随机排序。</p>
<h4>编码字符集</h4>
<p>如果采集的网站页面编码不是UTF-8，且无法自动识别，就需要手动填写了。</p>
<h4>时间间隔</h4>
<p>如果采集速度过快，有些网站会屏蔽你的服务器IP。</p>
<h4>使用代理服务器</h4>
<p>用来对付一些需要翻墙或容易被封IP的网站。</p>
<h4>远程发布</h4>
<p>为了有效缓解服务器的压力，可以将采集服务器和网站服务器分离。勾选此功能，采集到的文章将被推送到指定的网站。</p>
<p>属于要远程发布到的网站地址以及管理员的登录名和密码。</p>
<h4>重复判定</h4>
<p>可以选择判断重复的方式。</p>
<h4>避免空内容</h4>
<p>用于最终排查，如果采集到的所选内容是空的，则不保存。</p>
<h4>已排除的URL</h4>
<p>如果你想永久排除某些页面，请在这里输入URL，每行一个。</p>