<h2>导出收藏项目</h2>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/import&export/1.png" /></p>
<p>每一个收藏项目都有1个导出按钮，点击该按钮即可获得收藏项目代码，或者在该按钮上点击鼠标右键，选择另存为，将其保存为文件。</p>
<h2>导入收藏项目</h2>
<h4>导入到当前列表</h4>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/import&export/2.png" /></p>
<p>在收藏项目列表顶部有个<strong>导入收藏项目</strong>按钮，点击该按钮并输入收藏项目代码即可将其作为新收藏项目导入到项目列表中。</p>
<h4>导入到当前项目</h4>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/import&export/3.png" /></p>
<p>每一个收藏项目都有1个<strong>导入</strong>按钮，点击该按钮并输入收藏项目代码即可将其覆盖到当前项目中。</p>