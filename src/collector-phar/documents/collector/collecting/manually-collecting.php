<h2>功能按钮</h2>
<p>和测试从列表页采集内容不同的是，测试结果中的每个项目都有三个按钮：</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/collecting/manually-collecting/3.jpg" /></p>
<h4>采集按钮</h4>
<p>第1个按钮是采集按钮，图标是下载，点击后就会将该文章采集下来。</p>
<h4>忽略按钮</h4>
<p>第2个按钮是忽略按钮，图标是个叉，点击后则在本次采集过程中不会采集该文章。</p>
<h4>删除按钮</h4>
<p>第3个按钮是删除按钮，图标是个垃圾桶，点击后就会将该文章加入到<strong>已排除的URL</strong>列表中，即永远都不会采集这篇文章了，你可以到该收藏项目的采集设置里去删掉新增加的URL。</p>
<h2>小窍门</h2>
<p>双击忽略按钮或删除按钮，相当于全选，将会影响到所有的项目。</p>