<p>在收藏项目列表页点击导入链接按钮，即可弹出导入链接设置界面。</p>
<h2>设置</h2>
<p>导入链接设置分为两部分：</p>
<h4>设置导入链接</h4>
<p>首先选择导入的链接类型，一般都是文章链接，默认不需要修改。然后是输入要导入的文章链接，每行一个。</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/collecting/import-links/2.png" /></p>
<h4>保存设置</h4>
<p>默认会继承收藏项目设置中第一个来源链接采集的保存设置，你可以在这里修改。</p>
<p align="center"><img src="<?php print QQWORLD_COLLECTOR_DOCUMENTS_URL; ?>collector/collecting/import-links/3.png" /></p>
<p>一切准备妥当后点击 <strong>导入链接</strong> 按钮即可。</p>